#!/usr/bin/env node
/**
 * Split docs/legal/learnchinese_politica_privacidade_PT_EN_ES_ZH.md and
 * docs/legal/learnchinese_termos_de_uso_PT_EN_ES_ZH.md into per-locale markdown files
 * (pt, en, es, zh) and a bundled TS module for the app.
 *
 * Usage (repo root): node web/scripts/split-legal-content.mjs
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = join(__dirname, "..", "..");
const PRIVACY_SOURCE = join(REPO, "docs/legal/learnchinese_politica_privacidade_PT_EN_ES_ZH.md");
const TERMS_SOURCE = join(REPO, "docs/legal/learnchinese_termos_de_uso_PT_EN_ES_ZH.md");
const OUT_DIR = join(REPO, "web/src/content/legal");
const APP_OUT_DIR = join(REPO, "appMobile/ios/LearnChineseToday/Resources/Legal");

const PRIVACY_MARKERS = [
  { locale: "pt", header: "# POLÍTICA DE PRIVACIDADE — Português (Brasil)" },
  { locale: "en", header: "# PRIVACY POLICY — English" },
  { locale: "es", header: "# POLÍTICA DE PRIVACIDAD — Español" },
  { locale: "zh", header: "# 隐私政策 — 简体中文" },
];

const TERMS_MARKERS = [
  { locale: "pt", header: "# Termos de Uso — LearnChinese Today" },
  { locale: "en", header: "# Terms of Use — LearnChinese Today" },
  { locale: "es", header: "# Términos de Uso — LearnChinese Today" },
  { locale: "zh", header: "# 使用条款 — LearnChinese Today" },
];

function escapeForTs(str) {
  return str.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

function parseDoc(sourcePath, markers) {
  const raw = readFileSync(sourcePath, "utf8");
  const lines = raw.split("\n");
  const parsed = {};

  for (let i = 0; i < markers.length; i++) {
    const { locale, header } = markers[i];
    const startIdx = lines.findIndex((l) => l.trim() === header);
    if (startIdx < 0) {
      throw new Error(`[split-legal] Missing header in ${sourcePath}: ${header}`);
    }
    let endIdx = lines.length;
    if (i + 1 < markers.length) {
      const nextHeader = markers[i + 1].header;
      const found = lines.findIndex((l, idx) => idx > startIdx && l.trim() === nextHeader);
      if (found >= 0) endIdx = found;
    }

    let body = lines.slice(startIdx, endIdx).join("\n").trim();
    while (body.endsWith("---") || body.endsWith("\n") || body.endsWith("\r")) {
      body = body.replace(/[\r\n\-]+$/, "").trim();
    }
    parsed[locale] = body;
  }
  return parsed;
}

function main() {
  const privacy = parseDoc(PRIVACY_SOURCE, PRIVACY_MARKERS);
  const terms = parseDoc(TERMS_SOURCE, TERMS_MARKERS);

  mkdirSync(OUT_DIR, { recursive: true });
  mkdirSync(APP_OUT_DIR, { recursive: true });

  const locales = ["pt", "en", "es", "zh"];

  for (const loc of locales) {
    writeFileSync(join(OUT_DIR, `privacy.${loc}.md`), `${privacy[loc]}\n`, "utf8");
    writeFileSync(join(OUT_DIR, `terms.${loc}.md`), `${terms[loc]}\n`, "utf8");
    // Also save into app resources for offline bundling
    writeFileSync(join(APP_OUT_DIR, `privacy.${loc}.md`), `${privacy[loc]}\n`, "utf8");
    writeFileSync(join(APP_OUT_DIR, `terms.${loc}.md`), `${terms[loc]}\n`, "utf8");
  }

  const ts = `/** Auto-generated by web/scripts/split-legal-content.mjs — do not edit by hand. */
export type LegalKind = "privacy" | "terms";
export type LegalLocale = "pt" | "en" | "es" | "zh";

export const LEGAL_CONTENT: Record<LegalKind, Record<LegalLocale, string>> = {
  privacy: {
    pt: \`${escapeForTs(privacy.pt)}\`,
    en: \`${escapeForTs(privacy.en)}\`,
    es: \`${escapeForTs(privacy.es)}\`,
    zh: \`${escapeForTs(privacy.zh)}\`,
  },
  terms: {
    pt: \`${escapeForTs(terms.pt)}\`,
    en: \`${escapeForTs(terms.en)}\`,
    es: \`${escapeForTs(terms.es)}\`,
    zh: \`${escapeForTs(terms.zh)}\`,
  },
};
`;

  writeFileSync(join(OUT_DIR, "content.ts"), ts, "utf8");
  console.log(`[split-legal] Successfully wrote 8 markdown files + content.ts to ${OUT_DIR}`);
  console.log(`[split-legal] Mirrored 8 markdown files to ${APP_OUT_DIR}`);
}

main();
