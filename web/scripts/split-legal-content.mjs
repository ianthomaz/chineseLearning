#!/usr/bin/env node
/**
 * Split docs/legal/learnchinese-6-textos-legais.txt into per-locale markdown files
 * and a bundled TS module for the app (works in static export + server mode).
 *
 * Usage (repo root): node web/scripts/split-legal-content.mjs
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO = join(__dirname, "..", "..");
const SOURCE = join(REPO, "docs/legal/learnchinese-6-textos-legais.txt");
const OUT_DIR = join(REPO, "web/src/content/legal");

/** Header line → { kind, locale } */
const SECTIONS = [
  { marker: "POLÍTICA DE PRIVACIDADE — PT", kind: "privacy", locale: "pt" },
  { marker: "PRIVACY POLICY — EN", kind: "privacy", locale: "en" },
  { marker: "POLÍTICA DE PRIVACIDAD — ES", kind: "privacy", locale: "es" },
  { marker: "TERMOS DE USO — PT", kind: "terms", locale: "pt" },
  { marker: "TERMS OF USE — EN", kind: "terms", locale: "en" },
  { marker: "TÉRMINOS DE USO — ES", kind: "terms", locale: "es" },
];

function escapeForTs(str) {
  return str.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

function main() {
  const raw = readFileSync(SOURCE, "utf8");
  const lines = raw.split("\n");
  const parsed = {};

  for (let i = 0; i < SECTIONS.length; i++) {
    const { marker, kind, locale } = SECTIONS[i];
    const startIdx = lines.findIndex((l) => l.trim() === marker);
    if (startIdx < 0) {
      console.error(`[split-legal] Missing section: ${marker}`);
      process.exit(1);
    }
    const nextMarker = SECTIONS[i + 1]?.marker;
    let endIdx = lines.length;
    if (nextMarker) {
      const found = lines.findIndex((l, idx) => idx > startIdx && l.trim() === nextMarker);
      if (found >= 0) endIdx = found;
    }
    // Skip header line and trailing --- before next section
    let body = lines.slice(startIdx + 1, endIdx).join("\n").trim();
    body = body.replace(/\n---\s*$/, "").trim();

    parsed[`${kind}.${locale}`] = body;
    mkdirSync(OUT_DIR, { recursive: true });
    writeFileSync(join(OUT_DIR, `${kind}.${locale}.md`), `${body}\n`, "utf8");
  }

  const ts = `/** Auto-generated by web/scripts/split-legal-content.mjs — do not edit by hand. */
export type LegalKind = "privacy" | "terms";
export type LegalLocale = "pt" | "en" | "es";

export const LEGAL_CONTENT: Record<LegalKind, Record<LegalLocale, string>> = {
  privacy: {
    pt: \`${escapeForTs(parsed["privacy.pt"])}\`,
    en: \`${escapeForTs(parsed["privacy.en"])}\`,
    es: \`${escapeForTs(parsed["privacy.es"])}\`,
  },
  terms: {
    pt: \`${escapeForTs(parsed["terms.pt"])}\`,
    en: \`${escapeForTs(parsed["terms.en"])}\`,
    es: \`${escapeForTs(parsed["terms.es"])}\`,
  },
};
`;

  writeFileSync(join(OUT_DIR, "content.ts"), ts, "utf8");
  console.log(`[split-legal] Wrote 6 markdown files + content.ts → ${OUT_DIR}`);
}

main();
