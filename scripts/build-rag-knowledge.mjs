#!/usr/bin/env node
/**
 * Rebuild generated markdown under rag_knowledge/ from live course sources.
 * Hand-written pedagogical files in that folder are left untouched.
 *
 *   node scripts/build-rag-knowledge.mjs
 *
 * Does not call POST /ingest. Run `cd web && npm run ingest:rag` separately
 * when the local API should reindex.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const RAG = join(ROOT, "rag_knowledge");
const GENERATED_DIR = join(RAG, "generated");
const MARKER = "<!-- generated by scripts/build-rag-knowledge.mjs — do not edit -->";

const PHRASE_BUILT = join(ROOT, "web/src/data/phrase-game/phrases.json");
const PHRASE_CURATED = join(ROOT, "FRASES_GAME/curated/phrases.json");
const CONSOLIDADO = join(ROOT, "web/src/data/consolidado.json");
const VOCAB_BASICO = join(ROOT, "vocabulario/vocab-basico.json");
const QUIZ_BANK = join(ROOT, "web/src/data/gamification/hsk1-quiz-bank.json");
const BOOKS = join(ROOT, "OrganizeVocabulary_books/curated");

const EXTRA_AULAS = [
  {
    title: "Cozinha e culinária (aula China · 2026-08-26)",
    path: join(ROOT, "OrganizeVocabulary_books/china_lessons/2026-08-26_cozinha/Aula-cozinha.MD"),
  },
  {
    title: "Confúcio UNESP · Aula 3 — 明天打算干什么",
    path: join(ROOT, "OrganizeVocabulary_books/basic3_Confucius/Aula3.MD"),
  },
  {
    title: "Confúcio UNESP · Aula 4 — 打球",
    path: join(ROOT, "OrganizeVocabulary_books/basic3_Confucius/Aula4.MD"),
  },
];

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function writeGenerated(name, body) {
  mkdirSync(GENERATED_DIR, { recursive: true });
  const text = `${MARKER}\n\n${body.trim()}\n`;
  writeFileSync(join(GENERATED_DIR, name), text);
  return text.length;
}

function loadPhrases() {
  if (existsSync(PHRASE_BUILT)) {
    const bank = readJson(PHRASE_BUILT);
    return (bank.phrases ?? []).map((p) => ({
      id: p.id,
      nivel: p.nivel,
      tier: p.tier,
      hanzi: p.hanzi,
      pinyin: p.pinyin ?? "",
      pt: p.pt,
      en: p.en,
      es: p.es,
      pieces: (p.tokens ?? []).map((t) => t.palavra),
      alts: p.respostasAceitas ?? [],
      tags: p.tags ?? [],
    }));
  }
  const bank = readJson(PHRASE_CURATED);
  return (bank.phrases ?? []).map((p) => ({
    id: p.id,
    nivel: p.nivel,
    tier: p.tier,
    hanzi: (p.words ?? []).map((w) => w.palavra).join(""),
    pinyin: "",
    pt: p.pt,
    en: p.en,
    es: p.es,
    pieces: (p.words ?? []).map((w) => w.palavra),
    alts: p.respostasAceitas ?? [],
    tags: p.tags ?? [],
  }));
}

function buildPhraseGameMd(phrases) {
  const byTier = { hsk1: 0, basico: 0 };
  const entries = [];

  const sorted = [...phrases].sort((a, b) => a.id.localeCompare(b.id, "en", { numeric: true }));
  for (const p of sorted) {
    byTier[p.tier] = (byTier[p.tier] ?? 0) + 1;
    const tags = (p.tags ?? []).join(", ");
    entries.push(`## ${p.id}`);
    entries.push(`- hanzi: ${p.hanzi}`);
    if (p.pinyin) entries.push(`- pinyin: ${p.pinyin}`);
    entries.push(`- peças: ${p.pieces.join(" | ")}`);
    entries.push(`- PT: ${p.pt}`);
    if (p.en) entries.push(`- EN: ${p.en}`);
    if (p.es) entries.push(`- ES: ${p.es}`);
    entries.push(`- nível: ${p.nivel} · faixa: ${p.tier}${tags ? ` · ${tags}` : ""}`);
    if (p.alts.length) entries.push(`- ordens aceites: ${p.alts.join(" · ")}`);
    entries.push("");
  }

  const markdown = [
    "# Jogo de frases — banco completo",
    "",
    "Todas as frases do jogo de montar frases do site. Cada entrada é uma frase pedagógica",
    "com tradução PT/EN/ES. `peças` são os blocos que o aluno recebe.",
    "`ordens aceites` só lista permutações neutras de manual (quase sempre nenhuma).",
    "Não inventar outras ordens; não tratar tópico-comentário como alternativa.",
    "",
    `Por faixa: hsk1=${byTier.hsk1 ?? 0}, basico=${byTier.basico ?? 0}.`,
    `Total: **${phrases.length}** frases.`,
    "",
    ...entries,
  ].join("\n");

  return { markdown, counts: { total: phrases.length, ...byTier } };
}

function buildBooksMd() {
  const books = [
    { id: "primary-up", label: "新时代汉语口语 · 初级·上 (Level1.pdf)" },
    { id: "primary-down", label: "新时代汉语口语 · 初级·下 (level2.pdf)" },
  ];
  const lines = [
    "# Léxico curado dos livros",
    "",
    "Vocabulário das 32 lições de 新时代汉语口语 (初级·上 e 初级·下).",
    "Glosas em inglês vêm do livro; exemplos são os do PDF.",
    "",
  ];
  let entryCount = 0;
  let lessonCount = 0;

  for (const book of books) {
    const dir = join(BOOKS, book.id);
    if (!existsSync(dir)) continue;
    const files = readdirSync(dir)
      .filter((f) => /^lesson-\d+\.json$/.test(f))
      .sort();
    lines.push(`## ${book.label}`);
    lines.push("");

    for (const file of files) {
      const lesson = readJson(join(dir, file));
      const meta = lesson.meta ?? {};
      lessonCount += 1;
      lines.push(`### Lição ${meta.lesson ?? file} · ${meta.title ?? ""}`);
      lines.push("");

      const groups = lesson.byLessonSource ?? {};
      for (const [source, rows] of Object.entries(groups)) {
        if (!Array.isArray(rows) || rows.length === 0) continue;
        lines.push(`#### ${source}`);
        lines.push("");
        for (const row of rows) {
          entryCount += 1;
          const gloss = row.glossEn || row.glossPt || "";
          const pos = row.pos ? ` (${row.pos})` : "";
          lines.push(`- **${row.hanzi}** ${row.pinyin ?? ""}${pos} — ${gloss}`);
          if (Array.isArray(row.examples) && row.examples.length) {
            for (const ex of row.examples) lines.push(`  - ${ex}`);
          }
        }
        lines.push("");
      }
    }
  }

  lines.splice(4, 0, `Lições: **${lessonCount}**. Entradas (com repetição entre blocos da lição): **${entryCount}**.`, "");
  return { markdown: lines.join("\n"), lessonCount, entryCount };
}

function buildCourseVocabMd() {
  const { blocks = [] } = readJson(CONSOLIDADO);
  const lines = [
    "# Vocabulário e estruturas do curso (consolidado)",
    "",
    "Blocos editoriais do site: estruturas, notas e vocabulário com tradução em português.",
    "Inclui HSK1 e material extra (cozinha, etc.).",
    "",
  ];
  let vocabCount = 0;
  let structureCount = 0;

  for (const block of blocks) {
    lines.push(`## Bloco ${block.id} — ${block.title ?? ""}`);
    lines.push("");
    if (block.narrative && String(block.narrative).trim().length < 800) {
      lines.push(String(block.narrative).trim());
      lines.push("");
    }
    const structures = block.structures ?? [];
    if (structures.length) {
      lines.push("### Estruturas");
      for (const s of structures) {
        structureCount += 1;
        lines.push(`- ${s.hanzi}${s.pinyin ? ` · ${s.pinyin}` : ""}`);
      }
      lines.push("");
    }
    const notes = block.notes ?? [];
    if (notes.length) {
      lines.push("### Notas");
      for (const n of notes) lines.push(`- ${n}`);
      lines.push("");
    }
    const vocab = block.vocabulary ?? [];
    if (vocab.length) {
      lines.push("### Vocabulário");
      lines.push("| Hanzi | Pinyin | PT |");
      lines.push("|---|---|---|");
      for (const v of vocab) {
        vocabCount += 1;
        lines.push(`| ${v.hanzi} | ${v.pinyin ?? ""} | ${v.translation ?? ""} |`);
      }
      lines.push("");
    }
  }

  return { markdown: lines.join("\n"), blockCount: blocks.length, vocabCount, structureCount };
}

function buildAulasExtraMd() {
  const parts = [
    "# Aulas e conteúdo extra",
    "",
    "Material que não cabe só no HSK1: aula de cozinha e folhas Confúcio.",
    "Você pode acrescentar mais arquivos `.md` na raiz de `rag_knowledge/` — o ingest lê a pasta toda.",
    "",
  ];
  let included = 0;
  for (const aula of EXTRA_AULAS) {
    if (!existsSync(aula.path)) continue;
    included += 1;
    const body = readFileSync(aula.path, "utf8").trim();
    parts.push(`---\n\n# ${aula.title}\n\nFonte: \`${aula.path.replace(`${ROOT}/`, "")}\`\n\n${body}\n`);
  }
  return { markdown: parts.join("\n"), included };
}

function buildQuizVocabMd() {
  const lines = [
    "# Vocabulário do quiz (faixas HSK)",
    "",
    "Referência do banco de perguntas do quiz: vocabulário consolidado do curso,",
    "livros 初级·上/下, tokens do jogo de frases, flashcards e lexicon-base.",
    "Faixas cumulativas no quiz: HSK 2 inclui HSK 1, HSK 2+ inclui até 2+, etc.",
    "",
  ];

  if (existsSync(QUIZ_BANK)) {
    const bank = readJson(QUIZ_BANK);
    const meta = bank.metadata ?? {};
    lines.push(`Perguntas no banco: **${meta.total_questions ?? bank.questions?.length ?? 0}**.`);
    if (meta.unique_vocab) lines.push(`Hanzi distintos: **${meta.unique_vocab}**.`);
    if (meta.pool_exclusive) {
      lines.push(
        `Por faixa (exclusiva): hsk1=${meta.pool_exclusive.hsk1 ?? 0}, hsk2=${meta.pool_exclusive.hsk2 ?? 0}, hsk2plus=${meta.pool_exclusive.hsk2plus ?? 0}, hsk3=${meta.pool_exclusive.hsk3 ?? 0}.`,
      );
    }
    lines.push("");
    lines.push("## Amostra por faixa");
    lines.push("");
    for (const pool of ["hsk1", "hsk2", "hsk2plus", "hsk3"]) {
      const sample = (bank.questions ?? [])
        .filter((q) => q.pool === pool && q.hanzi)
        .slice(0, 12)
        .map((q) => q.hanzi)
        .join(", ");
      lines.push(`- **${pool}**: ${sample || "—"}`);
    }
    lines.push("");
  }

  if (existsSync(VOCAB_BASICO)) {
    const vb = readJson(VOCAB_BASICO);
    const entries = (vb.entries ?? []).filter((e) => e.hanzi && e.gloss_pt);
    lines.push(`## Lexicon-base + curso (${entries.length} entradas)`);
    lines.push("");
    lines.push("| Hanzi | Pinyin | PT | HSK1 |");
    lines.push("|---|---|---|---|");
    const sorted = [...entries].sort((a, b) => a.hanzi.localeCompare(b.hanzi, "zh"));
    for (const e of sorted.slice(0, 400)) {
      lines.push(`| ${e.hanzi} | ${e.pinyin ?? ""} | ${e.gloss_pt ?? ""} | ${e.hsk1 ? "sim" : ""} |`);
    }
    if (entries.length > 400) {
      lines.push("");
      lines.push(`_… e mais ${entries.length - 400} entradas no vocab-basico.json._`);
    }
  }

  return { markdown: lines.join("\n"), entryCount: readJson(VOCAB_BASICO).entries?.length ?? 0 };
}

function buildIndiceMd(stats) {
  return [
    "# Índice da base RAG (chinese_learning)",
    "",
    "Pasta `rag_knowledge/`. O tutor e o `/ask` devem usar este material como",
    "referência do **curso real**, não um HSK1 genérico.",
    "",
    "## Gerado (não editar)",
    "",
    `- \`generated/jogo-frases.md\` — ${stats.phrases.total} frases do jogo (hsk1=${stats.phrases.hsk1}, basico=${stats.phrases.basico})`,
    `- \`generated/livros.md\` — ${stats.books.lessonCount} lições, ${stats.books.entryCount} entradas dos PDFs 初级·上/下`,
    `- \`generated/vocabulario-curso.md\` — consolidado do site (${stats.course.blockCount} blocos, ${stats.course.vocabCount} palavras, ${stats.course.structureCount} estruturas)`,
    `- \`generated/aulas-extra.md\` — ${stats.aulas.included} aulas extra (cozinha, Confúcio)`,
    `- \`generated/quiz-vocab.md\` — vocabulário do quiz (${stats.quiz.entryCount} entradas lexicon + banco)`,
    "",
    "## Pedagógico (editar à mão)",
    "",
    "- `vocabulario_estruturas.md` — âncora rápida HSK1",
    "- `extraContent.md` — complemento HSK1 em tabelas",
    "- `dialogos_pratica.md` — diálogos de iniciante",
    "- `hsk1_interrogatives_pt.md` — perguntas (谁/什么/哪儿/…)",
    "- `ordem-alternativas.md` — quando uma ordem de frase é alternativa válida no jogo",
    "",
    "## Liberdade para mais conteúdo",
    "",
    "Qualquer `.md` extra na raiz de `rag_knowledge/` entra no próximo ingest.",
    "Não coloques rascunhos: o que estiver aqui é o que o modelo pode citar.",
    "Para corpora grandes gerados a partir de JSON, acrescenta uma fonte em",
    "`scripts/build-rag-knowledge.mjs` em vez de copiar à mão.",
    "",
    `Gerado em ${new Date().toISOString().slice(0, 10)}.`,
    "",
  ].join("\n");
}

function main() {
  mkdirSync(RAG, { recursive: true });

  const phrases = loadPhrases();
  const phraseMd = buildPhraseGameMd(phrases);
  const books = buildBooksMd();
  const course = buildCourseVocabMd();
  const aulas = buildAulasExtraMd();
  const quiz = buildQuizVocabMd();

  const sizes = {
    "jogo-frases.md": writeGenerated("jogo-frases.md", phraseMd.markdown),
    "livros.md": writeGenerated("livros.md", books.markdown),
    "vocabulario-curso.md": writeGenerated("vocabulario-curso.md", course.markdown),
    "aulas-extra.md": writeGenerated("aulas-extra.md", aulas.markdown),
    "quiz-vocab.md": writeGenerated("quiz-vocab.md", quiz.markdown),
    "indice.md": writeGenerated(
      "indice.md",
      buildIndiceMd({
        phrases: phraseMd.counts,
        books,
        course,
        aulas,
        quiz,
      }),
    ),
  };

  console.log("[rag] generated → rag_knowledge/generated/");
  for (const [name, bytes] of Object.entries(sizes)) {
    console.log(`  ${name}  ${(bytes / 1024).toFixed(1)} KB`);
  }
  console.log(
    `[rag] phrases=${phraseMd.counts.total}  book-lessons=${books.lessonCount}  course-blocks=${course.blockCount}  extra-aulas=${aulas.included}`,
  );
}

main();
